-- SQUELETTE DE SCHEMA POUR SUPABASE (à faire valider/configurer avant utilisation)
-- Ne pas utiliser en production sans avoir défini les rôles et politiques d'accès.
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null,
  role text not null default 'member' check (role in ('member','admin')),
  created_at timestamptz not null default now()
);

create table if not exists public.contributions (
  id bigint generated by default as identity primary key,
  member_id uuid not null references public.profiles(id) on delete cascade,
  contribution_year integer not null,
  month_number integer not null check (month_number between 1 and 12),
  expected_amount numeric(12,2) not null default 0 check (expected_amount >= 0),
  paid_amount numeric(12,2) not null default 0 check (paid_amount >= 0),
  note text,
  updated_at timestamptz not null default now(),
  unique(member_id, contribution_year, month_number)
);

create table if not exists public.documents (
  id bigint generated by default as identity primary key,
  title text not null,
  storage_path text not null,
  category text not null default 'general',
  uploaded_by uuid references public.profiles(id),
  created_at timestamptz not null default now()
);

alter table public.profiles enable row level security;
alter table public.contributions enable row level security;
alter table public.documents enable row level security;

